#!/usr/bin/env python3
"""
Pack the college map into files that can be uploaded to a CMS file manager as-is.

    python3 scripts/bundle.py

Writes:
    dist/dcp-college-map.bundle.js   one script: D3 + topojson + map shapes + data + logos + CSS + control
    dist/dcp-college-map.html        the same, as a standalone page for <iframe> embedding

Nothing in dist/ references any other file, so it works from any URL the host gives it.
Logos are shrunk to 96px and inlined as data URIs; the world map uses the lighter 110m shapes.
"""

import base64
import io
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WEB = ROOT / "web"
DIST = ROOT / "dist"
LOGO_PX = 96  # the tooltip shows logos at ~45 CSS px, so this stays sharp on 2x screens
_warned_no_pillow = False


def logo_data_uri(path):
    raw = path.read_bytes()
    if path.suffix == ".svg":
        return "data:image/svg+xml;base64," + base64.b64encode(raw).decode()
    try:
        from PIL import Image
        img = Image.open(io.BytesIO(raw)).convert("RGBA")
        if max(img.size) > LOGO_PX:
            img.thumbnail((LOGO_PX, LOGO_PX), Image.LANCZOS)
        buf = io.BytesIO()
        # a 256-colour palette is indistinguishable at this size and about a third of the bytes
        img.quantize(colors=256, method=Image.Quantize.FASTOCTREE).save(buf, "PNG", optimize=True)
        raw = buf.getvalue()
    except ImportError:
        global _warned_no_pillow
        if not _warned_no_pillow:
            _warned_no_pillow = True
            print("WARNING: Pillow is not installed, so logos are inlined at full size and the bundle "
                  "will be much larger. Run: pip install -r scripts/requirements.txt", file=sys.stderr)
    return "data:image/png;base64," + base64.b64encode(raw).decode()


def main():
    data = json.loads((WEB / "data" / "matriculation.json").read_text())
    for s in data["schools"]:
        if s.get("logo"):
            p = WEB / s["logo"]
            s["logo"] = logo_data_uri(p) if p.exists() else None
    css = (WEB / "dcp-college-map.css").read_text()
    control = (WEB / "dcp-college-map.js").read_text()
    d3 = (WEB / "vendor" / "d3.v7.min.js").read_text()
    topo = (WEB / "vendor" / "topojson-client.min.js").read_text()
    states = (WEB / "vendor" / "states-10m.json").read_text()
    countries = (WEB / "vendor" / "countries-110m.json").read_text()

    payload = "window.DCP_COLLEGE_MAP_BUNDLE = {\n  css: %s,\n  data: %s,\n  states: %s,\n  countries: %s\n};\n" % (
        json.dumps(css), json.dumps(data, ensure_ascii=False, separators=(",", ":")), states, countries)
    js = "\n".join([
        "/*! DePaul College Prep college map, single-file build. Generated by scripts/bundle.py. "
        "Includes D3 (ISC) and topojson-client (ISC). */",
        d3.rstrip() + ";", topo.rstrip() + ";", payload, control,
    ])
    DIST.mkdir(exist_ok=True)
    (DIST / "dcp-college-map.bundle.js").write_text(js)

    html = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Where DePaul Prep Graduates Attend College</title>
<meta name="robots" content="noindex">
<style>html,body{margin:0;padding:0;background:transparent}</style>
</head>
<body>
<div data-dcp-college-map></div>
<script>
%s
</script>
</body>
</html>
""" % js.replace("</script", "<\\/script")
    (DIST / "dcp-college-map.html").write_text(html)
    for f in ("dcp-college-map.bundle.js", "dcp-college-map.html"):
        print(f"wrote dist/{f}  ({(DIST / f).stat().st_size / 1024:.0f} KB)", file=sys.stderr)


if __name__ == "__main__":
    main()
